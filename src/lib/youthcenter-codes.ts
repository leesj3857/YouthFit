/** 콤마로 구분된 코드 문자열을 라벨 배열로. 모르는 코드는 원본 그대로 */
export function decodeCodes(raw: string, table: Record<string, string>): string[] {
  return raw
    .split(",")
    .map((c) => c.trim())
    .filter(Boolean)
    .map((c) => table[c] ?? c);
}
